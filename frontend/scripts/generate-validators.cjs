const fs = require('node:fs');
const path = require('node:path');
const Ajv2020 = require('ajv/dist/2020');
const standaloneCode = require('ajv/dist/standalone');

const src = path.resolve(__dirname, '../src');
const ajv = new Ajv2020({ allErrors: false, strict: false, code: { source: true, esm: true } });
ajv.addSchema(JSON.parse(fs.readFileSync(path.join(src, 'workspace-schema.json'), 'utf8')), 'workspace');
ajv.addSchema(JSON.parse(fs.readFileSync(path.join(src, 'error-schema.json'), 'utf8')), 'error');
const code = '// Generated by scripts/generate-validators.cjs; do not edit.\n' +
  standaloneCode(ajv, { validateSnapshot: 'workspace', validateError: 'error' });
const target = path.join(src, 'validators.mjs');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== code) {
    throw new Error('Stale standalone validators; run npm run generate:validators');
  }
} else {
  fs.writeFileSync(target, code);
}
